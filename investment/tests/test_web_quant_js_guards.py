    def test_domain_strategy_js_braces_balanced(self):
        """多余 } 会让 installStrategy 提前结束，return 变成模块顶层，/replay 整页 JS 挂不上。"""
        src = self._read("web", "static", "js", "quant", "domain_strategy.js")
        depth = 0
        in_s = None
        esc = False
        in_line = False
        in_block = False
        i = 0
        n = len(src)
        while i < n:
            c = src[i]
            nxt = src[i + 1] if i + 1 < n else ""
            if in_line:
                if c == "\n":
                    in_line = False
                i += 1
                continue
            if in_block:
                if c == "*" and nxt == "/":
                    in_block = False
                    i += 2
                    continue
                i += 1
                continue
            if in_s:
                if esc:
                    esc = False
                elif c == "\\":
                    esc = True
                elif c == in_s:
                    in_s = None
                i += 1
                continue
            if c in "\"'`":
                in_s = c
                i += 1
                continue
            if c == "/" and nxt == "/":
                in_line = True
                i += 2
                continue
            if c == "/" and nxt == "*":
                in_block = True
                i += 2
                continue
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                self.assertGreaterEqual(depth, 0, "extra } before end of domain_strategy.js")
            i += 1
        self.assertEqual(depth, 0)
        quant_js = self._read("web", "static", "js", "quant.js")
        self.assertIn(
            "domain_strategy.js?v=${encodeURIComponent(_QV)}",
            quant_js,
        )

